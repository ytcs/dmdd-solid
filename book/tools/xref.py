#!/usr/bin/env python3
"""Write tex/xref/vol{1,2,3}.tex: the labels each volume needs from the other two.

Usage: python3 tools/xref.py BUILD_DIR      (BUILD_DIR holds vol1.aux, vol2.aux, vol3.aux)
Exit status 0 when no xref file changed, 3 when at least one changed (rebuild the volumes).

Each entry is \\xrlabel{label}{data}; preamble.tex defines the label from it unless this volume defines the
label itself. Only labels that the volume references are kept. The hyperlink anchor of an external
label is replaced by Doc-Start (it lives in another PDF) and its page number is dropped (no \\pageref crosses
volumes), so the files change only when a number or a title changes; the number, the title and the cleveref
type are kept, so \\cref, \\crefrange, \\ref and \\nameref print as they would inside one volume.
"""
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import volumes as V  # noqa: E402


def groups(s):
    """Top-level brace groups of s."""
    out, depth, start = [], 0, None
    for i, c in enumerate(s):
        if c == "{" and (i == 0 or s[i - 1] != "\\"):
            if depth == 0:
                start = i
            depth += 1
        elif c == "}" and (i == 0 or s[i - 1] != "\\"):
            depth -= 1
            if depth == 0:
                out.append(s[start + 1:i])
    return out


def read_aux(path):
    labs = {}
    if not path.exists():
        return labs
    for line in path.read_text(errors="replace").splitlines():
        if not line.startswith("\\newlabel{"):
            continue
        g = groups(line[len("\\newlabel"):])
        if len(g) != 2:
            continue
        name, data = g
        if name.endswith("@cref"):
            labs[name] = "{%s}{[1][1][]1}" % groups(data)[0]
            continue
        f = groups(data)
        if len(f) == 5:
            data = "{%s}{}{%s}{Doc-Start}{}" % (f[0], f[2])
        labs[name] = data
    return labs


def referenced(vol):
    """Every comma-separated token inside braces in the source files of one volume (a superset of its references)."""
    toks = set()
    files = [f for _, fs in V.chapters(vol) for f in fs] + sorted((V.TEX / "front").glob("*.tex"))
    for f in files:
        for m in re.finditer(r"\{([^{}\\]+)\}", f.read_text()):
            for t in m.group(1).split(","):
                toks.add(t.strip())
    return toks


def main(build):
    build = Path(build)
    aux = {v: read_aux(build / f"{v}.aux") for v in V.VOLS}
    changed = False
    (V.TEX / "xref").mkdir(exist_ok=True)
    for v in V.VOLS:
        lines = ["% GENERATED by tools/xref.py from the .aux files of the other volumes; do not edit."]
        refd = referenced(v)
        for w in V.VOLS:
            if w == v:
                continue
            for name, data in aux[w].items():
                base = name[:-5] if name.endswith("@cref") else name
                if base in refd and name not in aux[v]:
                    lines.append("\\xrlabel{%s}{%s}" % (name, data))
        out = V.TEX / "xref" / f"{v}.tex"
        new = "\n".join(lines) + "\n"
        if not out.exists() or out.read_text() != new:
            out.write_text(new)
            changed = True
        print(f"{v}: {len(lines) - 1} external label entries")
    # every label of every volume, for tools/chapcheck.sh (not tracked by git, never read by a volume build)
    seen, lines = set(), ["% GENERATED by tools/xref.py; every label of the three volumes, for tools/chapcheck.sh."]
    for w in V.VOLS:
        for name, data in aux[w].items():
            if name not in seen:
                seen.add(name)
                lines.append("\\xrlabel{%s}{%s}" % (name, data))
    (V.TEX / "xref" / "all.tex").write_text("\n".join(lines) + "\n")
    return 3 if changed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
