#!/usr/bin/env python3
"""Split the generated list of symbols (tex/appB/B-1.tex) into one list per volume.

Usage: python3 tools/split_B1.py
Reads tex/appB/B-1.tex (written by figscripts/appB/gen_B1.py from NOTATION.md) and writes
tex/appB/B-1-vol{1,2,3}.tex. A symbol goes to the volume that holds the section of its first use and is
listed under the chapter that holds that section now; within a chapter the rows keep the order of the
chapter's sections and, within a section, the order of B-1.tex. Appendix A is in every volume, and its
symbols are listed in every volume. Rerun after gen_B1.py or after moving a section.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import volumes as V  # noqa: E402

SRC = V.TEX / "appB" / "B-1.tex"
# First-use labels of the one-volume edition whose sections were folded into chapters in the three-volume edition.
MOVED = {"app:D.15": "sec:5.6", "app:D.17": "sec:6.4", "app:D.18": "sec:6.5", "app:D.19": "sec:7.1",
         "app:D.29": "sec:10.1", "app:D.41": "sec:16.1"}
NUM = {"vol1": "I", "vol2": "II", "vol3": "III"}


def main():
    lines = SRC.read_text().splitlines()
    first = next(i for i, s in enumerate(lines) if s.startswith("\\addlinespace[4pt]"))
    last = next(i for i, s in enumerate(lines) if s.startswith("\\end{longtable}"))
    head, tail = lines[:first], lines[last:]
    rows = [s for s in lines[first:last] if "\\labelcref{" in s]
    stray = [s for s in lines[first:last] if "\\labelcref{" not in s and not s.startswith(("\\addlinespace", "\\multicolumn"))]
    if stray:
        sys.exit("rows without a first-use label:\n" + "\n".join(stray))
    home = V.label_home()
    dropped = set()
    for vol in V.VOLS:
        order = {}      # label -> (chapter index, position in chapter)
        chlabel = []
        for ci, (driver, files) in enumerate(V.chapters(vol)):
            chlabel.append(V.chapter_label(driver))
            pos = 0
            for f in files:
                for lab in V.labels_of(f):
                    order.setdefault(lab, (ci, pos))
                    pos += 1
        by_ch = defaultdict(list)
        for k, row in enumerate(rows):
            lab = re.findall(r"\\labelcref\{([^}]+)\}", row)[-1]
            if lab in MOVED:
                row = row.replace("\\labelcref{%s}" % lab, "\\labelcref{%s}" % MOVED[lab])
                lab = MOVED[lab]
            if lab not in home:
                dropped.add(row)
                continue
            if lab in order:
                ci, pos = order[lab]
                by_ch[ci].append((pos, k, row))
        out = [s.replace("GENERATED by figscripts/appB/gen_B1.py",
                         "GENERATED by figscripts/appB/gen_B1.py and tools/split_B1.py") for s in head]
        intro = next(i for i, s in enumerate(out) if s.startswith("Each symbol is listed once"))
        out[intro] = (f"The list holds the symbols first used in Volume~{NUM[vol]}; a symbol first used in another volume is "
                      "listed there. " + out[intro])
        n = 0
        for ci in sorted(by_ch):
            lab = chlabel[ci]
            kind = "Appendix" if lab.startswith("app:") else "Chapter"
            out += ["\\addlinespace[4pt]",
                    "\\multicolumn{4}{@{}l}{\\bfseries %s~\\ref{%s}: \\nameref{%s}}\\\\*" % (kind, lab, lab),
                    "\\addlinespace[2pt]"]
            for _, _, row in sorted(by_ch[ci]):
                out.append(row)
                n += 1
        out += tail
        (V.TEX / "appB" / f"B-1-{vol}.tex").write_text("\n".join(out) + "\n")
        print(f"{vol}: {n} symbol rows in {len(by_ch)} groups")
    if dropped:
        print(f"{len(dropped)} rows dropped: first-use section no longer exists (update NOTATION.md and rerun gen_B1.py)")
        for row in sorted(dropped):
            print("   ", row[:120])


if __name__ == "__main__":
    main()
