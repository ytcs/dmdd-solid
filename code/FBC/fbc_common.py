# ---------------------------------------------------------------- grid and symmetry
def oh_ops():
    """48 proper/improper cubic rotations (cartesian, integer matrices)."""
    import itertools
    ops = []
    for perm in itertools.permutations(range(3)):
        for signs in itertools.product((1, -1), repeat=3):
            M = np.zeros((3, 3), int)
            for i in range(3):
                M[i, perm[i]] = signs[i]
            ops.append(M)
    return np.array(ops)


class Grid:
    """Gamma-centred n^3 grid k = (i . B)/n, i in [0, n)^3 (B rows = fcc reciprocal primitive vectors, 2pi/a)."""

    def __init__(self, n):
        self.n = n
        i = np.array(np.meshgrid(*[np.arange(n)] * 3, indexing="ij")).reshape(3, -1).T
        self.i = i                                   # (N, 3) integer coords
        self.N = len(i)
        # shortest representative of each grid point (reduced coords kr, cartesian k): the EPM basis is a fixed
        # G sphere, so H(k) is evaluated at the 1BZ representative to keep E(Rk) = E(k) exact
        r = range(-2, 3)
        mm = np.array([(a, b, c) for a in r for b in r for c in r])
        cand = (i[:, None, :] / n + mm[None]) @ B
        d = (cand ** 2).sum(-1)
        best = np.argmin(d + 1e-9 * np.arange(len(mm))[None], axis=1)
        self.kr = i / n + mm[best]                   # reduced, shortest
        self.k = self.kr @ B                         # cartesian, 2pi/a
        self.Binv = np.linalg.inv(B)
        # symmetry: cartesian op R acts on reduced coords as i' = i (B R^T B^-1)
        self.ops = oh_ops()
        self.Mred = np.array([np.rint(B @ R.T @ self.Binv).astype(int) for R in self.ops])
        assert all(np.allclose(B @ R.T @ self.Binv, M) for R, M in zip(self.ops, self.Mred))
        self.perm = np.array([self.index(self.i @ M) for M in self.Mred])     # (48, N): op o maps k_j -> k_perm[o, j]
        # irreducible representatives: smallest index in each star
        star_min = self.perm.min(0)
        self.irr = np.unique(star_min)
        self.irr_of = np.searchsorted(self.irr, star_min)                      # (N,) position in self.irr
        # op taking the representative to each point: perm[o, irr[irr_of[j]]] == j
        self.op_from_irr = np.empty(self.N, int)
        for j in range(self.N):
            r = self.irr[self.irr_of[j]]
            self.op_from_irr[j] = int(np.where(self.perm[:, r] == j)[0][0])
        self.weight = np.bincount(self.irr_of, minlength=len(self.irr))
        # representative vector of every point = R_o (representative of its irreducible point), so that energies and
        # wave functions generated by rotation are exactly symmetric (also at zone-boundary ties)
        for j in range(self.N):
            r_ = self.irr[self.irr_of[j]]
            R = self.ops[self.op_from_irr[j]]
            self.kr[j] = (R @ (self.kr[r_] @ B)) @ self.Binv
            assert np.allclose(np.mod(self.kr[j] * n + 1e-9, n) - 1e-9, self.i[j], atol=1e-6)
        self.k = self.kr @ B

    def index(self, i):
        i = np.mod(np.asarray(i), self.n)
        return (i[..., 0] * self.n + i[..., 1]) * self.n + i[..., 2]

    def umk(self, kY, Qred, kX):
        """integer reduced vector G_U = k_Y + Q - k_X (shortest representatives); asserts integrality."""
        b = self.kr[kY] + Qred - self.kr[kX]
        r_ = np.rint(b).astype(int)
        assert np.allclose(b, r_, atol=1e-9)
        return r_

    def fold(self, isum):
        """integer coords (any) -> (index of folded point, Umklapp in reduced reciprocal coords)."""
        f = np.mod(isum, self.n)
        return self.index(f), (isum - f) // self.n


def nonsymm_t(VS=None):
    """fractional translations t_o (cartesian, units of a) of the diamond space group for the 48 Oh matrices, with the
    origin at the bond centre (atoms at +-tau): the op r -> R r + t leaves the EPM potential invariant,
    U(R^-1 G) e^{-i 2 pi G.t} = U(G).  Verified numerically on all |G|^2 <= 11 shells."""
    tau = np.array([1, 1, 1]) / 8.0
    _, Gc = gset(11)
    vs = VS or {3: -0.21, 8: 0.04, 11: 0.08}
    def U(G):
        s = np.rint((G ** 2).sum(-1)).astype(int)
        return np.array([vs.get(int(x), 0.0) for x in s]) * np.cos(2 * np.pi * (G @ tau))
    ts = []
    for R in oh_ops():
        for t in (np.zeros(3), tau - R @ tau, -tau - R @ tau):
            if np.allclose(U(Gc @ R) * np.exp(-2j * np.pi * (Gc @ t)), U(Gc)):
                ts.append(t)
                break
        else:
            raise RuntimeError("no fractional translation found")
    return np.array(ts)


# ---------------------------------------------------------------- plane-wave bookkeeping
class PW:
    """The EPM basis G (cartesian, 2pi/a) in reduced coords m (G = m . B) with a dense lookup table for shifts."""

    def __init__(self, si):
        self.G = si.G
        self.m = np.rint(si.G @ np.linalg.inv(B)).astype(int)
        assert np.allclose(self.m @ B, si.G)
        self.npw = len(self.G)
        self.off = 16
        L = 2 * self.off + 1
        self.lut = -np.ones((L, L, L), int)
        mm = self.m + self.off
        self.lut[mm[:, 0], mm[:, 1], mm[:, 2]] = np.arange(self.npw)

    def shifted(self, shift):
        """indices of g - shift for every basis g (npw,), -1 where outside the basis; shift in reduced coords."""
        mm = self.m - np.asarray(shift) + self.off
        ok = np.all((mm >= 0) & (mm < 2 * self.off + 1), axis=-1)
        out = -np.ones(mm.shape[:-1], int)
        out[ok] = self.lut[mm[ok, 0], mm[ok, 1], mm[ok, 2]]
        return out


def gset(maxshell=8):
    """reciprocal vectors with |G|^2 <= maxshell (2pi/a)^2, reduced coords and cartesian."""
    r = range(-4, 5)
    m = np.array([(a, b, c) for a in r for b in r for c in r])
    G = m @ B
    s = np.rint((G ** 2).sum(1)).astype(int)
    keep = s <= maxshell
    order = np.argsort(s[keep], kind="stable")
    return m[keep][order], G[keep][order]


# ---------------------------------------------------------------- bands
def model_edges(si):
    """VBM at Gamma; CBM = minimum of band 5 on Gamma-X (coarse scan then bounded refinement)."""
    from scipy.optimize import minimize_scalar
    gx = np.linspace(0, 1, 101)
    eb = si.bands(gx[:, None] * np.array([1.0, 0, 0]), nb=6)[:, 4]
    i = int(eb.argmin())
    f = lambda x: si.bands(np.array([[x, 0, 0]]), nb=6)[0, 4]
    r = minimize_scalar(f, bounds=(gx[max(i - 1, 0)], gx[min(i + 1, 100)]), method="bounded", options=dict(xatol=1e-5))
    evbm = si.bands(np.zeros((1, 3)), nb=4)[0, 3]
    return evbm, r.fun, r.x


def make_epm(variant="scissor"):
    """variant 'scissor': book form factors + rigid scissor to EG.  variant 'refit': V_S(3), V_S(8), V_S(11)
    adjusted (see bands.py) so that the indirect gap is EG without a scissor."""
    si = EPM("Si")
    if variant == "refit":
        vs = json_load(os.path.join(DATA, "refit_formfactors.json"))["VS"]
        si = EPM_custom({int(k): v for k, v in vs.items()})
    return si


def EPM_custom(VS):
    MATERIALS["Si_fit"] = dict(a=A_LAT, VS=VS, VA={})
    return EPM("Si_fit")


def json_load(p):
    import json
    with open(p) as fh:
        return json.load(fh)


def grid_bands(n, nb, variant="scissor", force=False):
    """eigenpairs on the full n^3 grid. Returns dict with E (N, nb) [eV, relative to VBM, scissored], C (N, npw, nb),
    Eraw (unscissored), and the edges."""
    path = os.path.join(WORK, f"bands_{variant}_n{n}_nb{nb}.npz")
    if os.path.exists(path) and not force:
        d = np.load(path)
        return {k: d[k] for k in d.files}
    si = make_epm(variant)
    evbm, ecbm, kcbm = model_edges(si)
    gmodel = ecbm - evbm
    delta = EG - gmodel if variant == "scissor" else 0.0
    g = Grid(n)
    E = np.zeros((g.N, nb))
    C = np.zeros((g.N, len(si.G), nb), complex)
    w, v = np.linalg.eigh(si.hamiltonian(g.k[g.irr]))
    Ei, Ci = w[:, :nb] * RY, v[:, :, :nb]
    # rotate: c_{Rk}(G') = c_k(R^-1 G') e^{-i 2pi (Rk + G').t}
    VS = None
    if variant == "refit":
        VS = {int(k): x for k, x in json_load(os.path.join(DATA, "refit_formfactors.json"))["VS"].items()}
    ts = nonsymm_t(VS)
    pw = PW(si)
    key = {tuple(m): i_ for i_, m in enumerate(pw.m)}
    Binv = np.linalg.inv(B)
    permG = []
    for R in g.ops:
        permG.append(np.array([key[tuple(np.rint((R.T @ G) @ Binv).astype(int))] for G in si.G]))
    for j in range(g.N):
        r_ = g.irr_of[j]
        o = g.op_from_irr[j]
        E[j] = Ei[r_]
        ph = np.exp(-2j * np.pi * ((g.k[j][None, :] + si.G) @ ts[o]))
        C[j] = Ci[r_][permG[o]] * ph[:, None]
    Eraw = E - evbm
    E = Eraw.copy()
    E[:, NV:] += delta
    out = dict(E=E, Eraw=Eraw, C=C, delta=np.array(delta), gmodel=np.array(gmodel), kcbm=np.array(kcbm),
               ecbm=np.array(gmodel + delta), n=np.array(n))
    np.savez(path, **out)
    return out


# ---------------------------------------------------------------- screening (static, diagonal)
def eps_cappellini(qA, eps0=EPS0_SI, alpha_c=1.563):
    """Cappellini, Del Sole, Reining, Bechstedt, PRB 47, 9892 (1993) model (quoted form):
    eps(q) = 1 + 1/[1/(eps0-1) + alpha (q/q_TF)^2 + q^4/(4 omega_p^2) (hbar^2/2m)^2... ] in atomic-like units.
    Implemented as eps = 1 + 1/(1/(eps0-1) + alpha*(q/qTF)^2 + (hbar^2 q^2/2m)^2/omega_p^2)."""
    n = 8 / OMEGA                                      # valence electrons per A^3
    hb2m = 3.80998212                                  # hbar^2/2m_e, eV A^2
    wp = np.sqrt(4 * np.pi * n * E2 * 2 * hb2m)        # plasma energy, eV  (hbar^2 4 pi n e^2/m)
    kF = (3 * np.pi ** 2 * n) ** (1 / 3)
    qTF = np.sqrt(4 * kF / (np.pi * 0.529177210544))   # Thomas-Fermi wave vector (1/A), a0 in A
    return 1 + 1 / (1 / (eps0 - 1) + alpha_c * (qA / qTF) ** 2 + (hb2m * qA ** 2) ** 2 / wp ** 2)


def eps_resta(qA, eps0=EPS0_SI, R=4.27):
    """Resta, PRB 16, 2717 (1977) static model for Si (quoted form): for q < ... eps(q) =
    [q0^2 + q^2] / [q0^2 sin(qR)/(eps0 qR) + q^2] for q < pi/R and the Thomas-Fermi 1 + q0^2/q^2 beyond (continuous),
    q0 = Thomas-Fermi wave vector of the valence density, R = 4.27 bohr (Si)."""
    n = 8 / OMEGA
    kF = (3 * np.pi ** 2 * n) ** (1 / 3)
    q0 = np.sqrt(4 * kF / (np.pi * 0.529177210544))
    RA = R * 0.529177210544
    x = np.maximum(qA * RA, 1e-12)
    e = (q0 ** 2 + qA ** 2) / (q0 ** 2 * np.sin(x) / (eps0 * x) + qA ** 2)
    return np.where(qA * RA < np.pi, e, 1 + q0 ** 2 / np.maximum(qA, 1e-12) ** 2)


SCREEN = {"cap": eps_cappellini, "resta": eps_resta}


def vscr(qA, model="cap"):
    """screened Coulomb kernel w(q) = 4 pi e^2/(eps(q) q^2), eV A^3."""
    if model == "bare":
        return 4 * np.pi * E2 / qA ** 2
    return 4 * np.pi * E2 / (SCREEN[model](qA) * qA ** 2)
